"""Program-of-Thought (PoT) reasoning engine.

Instead of asking the LLM to compute arithmetic directly (prone to
hallucination), this engine instructs the LLM to generate a short Python
program that extracts values and performs calculations.  The generated
code is then executed in a safe sandbox for 100% arithmetic accuracy.

Enhanced to support multi-provider LLMs (Google Gemini & LLaMA API).
"""

from __future__ import annotations

import re
from typing import Any

from financial_rag.config.settings import Settings
from financial_rag.reasoning.llm_client import UnifiedLLMClient
from financial_rag.reasoning.sandbox import execute_python_safely


# ---------------------------------------------------------------------------
# Prompts
# ---------------------------------------------------------------------------

PROGRAM_GENERATION_PROMPT = """You are a financial computation assistant.  Given financial context (text and tables) and a question, write a short Python program that:

1. **Extracts** the relevant numeric values from the provided context and assigns them to clearly named variables.
2. **Performs** the required calculation step-by-step.
3. **Assigns** the final answer to a variable called `ans`.

Rules:
- Write ONLY executable Python code.  Do NOT include explanations or markdown fences.
- Use only basic arithmetic operators: +, -, *, /, round, abs, min, max, sum, len.
- All numbers must come directly from the context.
- For percentages, multiply by 100 and round to 2 decimal places (e.g. `ans = round(ratio * 100, 2)`).
- For growth rate: `ans = round((new - old) / abs(old) * 100, 2)`.
- If the required data is NOT in the context, set `ans = None`.

### Context:
{context}

### Question:
{question}

### Python Program:
"""


# ---------------------------------------------------------------------------
# Question classification
# ---------------------------------------------------------------------------

_QUANT_PATTERNS = [
    re.compile(r"\b(what\s+is|calculate|compute|find|determine)\b.*?\b(growth|rate|percentage|ratio|change|margin|difference|total|sum|average|mean)\b", re.IGNORECASE),
    re.compile(r"\b(how\s+much|how\s+many|what\s+percentage)\b", re.IGNORECASE),
    re.compile(r"\b(tỷ\s*lệ|bao\s*nhiêu|tăng\s*trưởng|chênh\s*lệch|tính\s*toán)\b", re.IGNORECASE),
    re.compile(r"[\d]+(?:\.\d+)?\s*%", re.IGNORECASE),
    re.compile(r"\b(increased|decreased|grew|fell|declined)\s+by\b", re.IGNORECASE),
]


def is_quantitative_question(question: str) -> bool:
    """Determine whether a question requires mathematical computation."""
    if not question:
        return False
    for pattern in _QUANT_PATTERNS:
        if pattern.search(question):
            return True
    # Also check for presence of numbers in the question (e.g., "2018 to 2019")
    years = re.findall(r"\b(19|20)\d{2}\b", question)
    if len(years) >= 2:
        return True
    return False


class ProgramOfThoughtEngine:
    """Generates and executes Python programs for financial QA."""

    def __init__(self, settings: Settings, llm_client: UnifiedLLMClient | None = None):
        self.settings = settings
        self.llm_client = llm_client or UnifiedLLMClient(settings)

    @property
    def genai_client(self) -> Any:
        return self.llm_client.genai_client

    @genai_client.setter
    def genai_client(self, value: Any) -> None:
        self.llm_client.genai_client = value

    def generate_program(self, question: str, context: str) -> str:
        """Ask the LLM to generate a Python computation program.

        Returns the raw Python source code string.
        """
        prompt = PROGRAM_GENERATION_PROMPT.format(
            context=context[:8000],  # truncate very long contexts
            question=question,
        )

        code = self.llm_client.generate_text(
            prompt=prompt,
            temperature=0.0,  # deterministic for computation
        )

        # Strip markdown code fences if the LLM included them
        code = re.sub(r"^```(?:python)?\s*\n?", "", code, flags=re.MULTILINE)
        code = re.sub(r"\n?```\s*$", "", code, flags=re.MULTILINE)

        return code.strip()

    def solve(
        self,
        question: str,
        context: str,
        timeout: int = 10,
    ) -> dict[str, Any]:
        """Generate a program, execute it, and return the result.

        Returns a dictionary with:
        - "success": bool
        - "answer": the computed value (or None)
        - "generated_code": the raw Python code generated by the LLM
        - "error": error message if execution failed (or None)
        """
        code = self.generate_program(question, context)

        if not code:
            return {
                "success": False,
                "answer": None,
                "generated_code": "",
                "error": "LLM failed to generate a program.",
            }

        exec_result = execute_python_safely(code, timeout=timeout)

        if not exec_result["success"]:
            return {
                "success": False,
                "answer": None,
                "generated_code": code,
                "error": exec_result.get("error", "Execution failed"),
            }

        return {
            "success": True,
            "answer": exec_result["result"],
            "generated_code": code,
            "error": None,
            "execution_time": exec_result.get("execution_time", 0.0),
        }
